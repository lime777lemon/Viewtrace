import { copy as i18nCopy, type Locale } from "@/lib/i18n";
import {
  isStructuredFinding,
  presentObservationAiAudit,
  type ObservationAiAudit,
} from "@/lib/observation-ai-audit";
import {
  aiAuditEvidenceLabel,
  aiAuditImpactLabel,
  observationAiAuditCopyFrom,
} from "@/lib/observation-ai-audit-copy";

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/** メールに載せる指摘の上限。全部は記録側で読む。 */
const EMAIL_NOTE_LIMIT = 5;

/**
 * Watch の Alert メールに添える Change Audit。
 * 位置づけは記録の下の「読み（推定）」。Observed とは分けて見出しに明記する。
 */
export function changeAuditEmailSection(
  audit: ObservationAiAudit,
  input: { locale?: Locale; recordUrl: string },
): { text: string[]; html: string } {
  const locale: Locale = input.locale ?? "ja";
  const ja = locale === "ja";
  const t = observationAiAuditCopyFrom(i18nCopy[locale].observationDetail);
  const shown = presentObservationAiAudit(audit, locale);
  const notes = shown.notes.filter(isStructuredFinding).slice(0, EMAIL_NOTE_LIMIT);
  const more = Math.max(0, shown.notes.filter(isStructuredFinding).length - notes.length);

  const heading = ja
    ? "Change Audit（AI の読み。観測事実ではありません）"
    : "Change Audit (AI reading, not Observed)";
  const sourceLine =
    shown.source === "ai"
      ? ja
        ? `生成: AI（${shown.model ?? "model"}）。記録の事実を読んだ推定です。`
        : `Generated by AI (${shown.model ?? "model"}) from the recorded facts. This is an inference.`
      : ja
        ? "生成: 記録からの機械的な指摘のみ（AI 未設定）。"
        : "Record-based notes only (AI not configured).";

  const text: string[] = ["", heading, shown.summary, sourceLine];
  for (const note of notes) {
    const impact = note.impact ? aiAuditImpactLabel(t, note.impact) : "";
    const evidence = note.evidence ? aiAuditEvidenceLabel(t, note.evidence) : "";
    text.push("", `- ${impact ? `[${impact}] ` : ""}${note.text}`);
    if (evidence) text.push(`  ${t.evidence}: ${evidence}`);
    if (note.check) text.push(`  ${t.recommendedCheck}: ${note.check}`);
  }
  if (more > 0) {
    text.push("", ja ? `ほか ${more} 件は記録で確認できます。` : `${more} more note(s) on the record.`);
  }
  text.push(ja ? `記録の監査欄: ${input.recordUrl}` : `Audit on the record: ${input.recordUrl}`);

  const htmlNotes = notes
    .map((note) => {
      const impact = note.impact ? aiAuditImpactLabel(t, note.impact) : "";
      const evidence = note.evidence ? aiAuditEvidenceLabel(t, note.evidence) : "";
      return [
        '<li style="margin:0 0 8px;">',
        impact ? `<strong>[${escapeHtml(impact)}]</strong> ` : "",
        escapeHtml(note.text),
        evidence
          ? `<br/><span style="color:#555;">${escapeHtml(t.evidence)}: ${escapeHtml(evidence)}</span>`
          : "",
        note.check
          ? `<br/><span style="color:#555;">${escapeHtml(t.recommendedCheck)}: ${escapeHtml(note.check)}</span>`
          : "",
        "</li>",
      ].join("");
    })
    .join("");

  const html = [
    '<div style="margin:16px 0 0;padding:12px 14px;border:1px solid #d9d9e3;border-radius:8px;background:#fafafd;">',
    `<p style="margin:0 0 6px;font-weight:600;">${escapeHtml(heading)}</p>`,
    `<p style="margin:0 0 6px;">${escapeHtml(shown.summary)}</p>`,
    `<p style="margin:0 0 8px;font-size:12px;color:#555;">${escapeHtml(sourceLine)}</p>`,
    htmlNotes ? `<ul style="margin:0;padding-left:18px;">${htmlNotes}</ul>` : "",
    more > 0
      ? `<p style="margin:8px 0 0;font-size:12px;color:#555;">${escapeHtml(
          ja ? `ほか ${more} 件は記録で確認できます。` : `${more} more note(s) on the record.`,
        )}</p>`
      : "",
    `<p style="margin:8px 0 0;font-size:12px;"><a href="${escapeHtml(input.recordUrl)}" style="color:#2563eb;">${escapeHtml(
      ja ? "記録の監査欄を開く" : "Open the audit on the record",
    )}</a></p>`,
    "</div>",
  ].join("");

  return { text, html };
}
