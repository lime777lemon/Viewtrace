import * as esbuild from "esbuild";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));

const result = await esbuild.build({
  entryPoints: [path.join(root, "../src/lib/interaction-engine/browserless/hover-browserless-entry.ts")],
  bundle: true,
  format: "iife",
  globalName: "ViewTraceHoverEngine",
  platform: "neutral",
  target: "es2020",
  write: false,
  plugins: [
    {
      name: "viewtrace-ts-paths",
      setup(build) {
        build.onResolve({ filter: /^@\// }, (args) => {
          const base = path.join(root, "../src", args.path.slice(2));
          return { path: base.endsWith(".ts") ? base : `${base}.ts` };
        });
      },
    },
  ],
});

const js = result.outputFiles[0].text;
const outPath = "src/lib/interaction-engine/generated/hover-engine-browserless-runtime.ts";
writeFileSync(
  outPath,
  `/** Generated by scripts/bundle-interaction-engine-hover.mjs — do not edit. */\nexport const HOVER_ENGINE_BROWSERLESS_RUNTIME = ${JSON.stringify(js)};\n`,
);
console.error(`wrote ${outPath} (${js.length} bytes)`);
