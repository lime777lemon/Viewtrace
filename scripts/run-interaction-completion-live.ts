/**
 * Production Regional Interaction Check against per-type fixtures.
 * Records only what Browserless returned. Does not invent Before/After.
 *
 * Jobs: 25 types × (US-CA working/broken/absent/unsafe + US-FL working + JP-13 working).
 * Resume: tmp/interaction-live-results.json
 * Ledger: src/lib/interaction-completion-runs.ts (gates are derived from these rows)
 *
 * FIXTURE_JOB=scroll or scroll:US-CA:working
 * CONCURRENCY=3
 */
import { mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { interactionFixtureDocument } from "../src/lib/interaction-test-fixtures";
import {
  INTERACTION_COMPLETION_GATES,
  deriveInteractionCompletion,
  framesDiffer,
  noteShowsDelta,
  snapshotsDiffer,
  type InteractionRunMode,
  type InteractionRunRegion,
  type RecordedInteractionRun,
} from "../src/lib/interaction-completion";
import {
  INTERACTION_CHECK_TYPES,
  type InteractionCheckType,
} from "../src/lib/observation-regional-interaction";

function loadEnvLocal() {
  let text = "";
  try {
    text = readFileSync(".env.local", "utf8");
  } catch {
    return;
  }
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq < 1) continue;
    const key = trimmed.slice(0, eq);
    let value = trimmed.slice(eq + 1);
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] == null) process.env[key] = value;
  }
}

loadEnvLocal();

const RESULTS_PATH = "tmp/interaction-live-results.json";
const LEDGER_PATH = "src/lib/interaction-completion-runs.ts";
const MATRIX_PATH = "tmp/interaction-completion-matrix.txt";

type LiveRow = RecordedInteractionRun & {
  error: string | null;
  detail: string | null;
  duration_ms: number | null;
  evidence_selector: string | null;
  changes: string[];
  note: string | null;
  frame_hashes: string[] | null;
  t0: unknown;
  t1: unknown;
};

type Job = { type: InteractionCheckType; region: InteractionRunRegion; mode: InteractionRunMode };

function allJobs(): Job[] {
  const modes: InteractionRunMode[] = ["working", "broken", "absent", "unsafe"];
  const jobs: Job[] = [];
  for (const type of INTERACTION_CHECK_TYPES) {
    for (const mode of modes) jobs.push({ type, region: "US-CA", mode });
    jobs.push({ type, region: "US-FL", mode: "working" });
    jobs.push({ type, region: "JP-13", mode: "working" });
  }
  return jobs;
}

function jobKey(job: { type: string; region: string; mode: string }) {
  return `${job.type}:${job.region}:${job.mode}`;
}

function loadRows(): LiveRow[] {
  try {
    const parsed = JSON.parse(readFileSync(RESULTS_PATH, "utf8")) as LiveRow[];
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

function blank(job: Job, error: string, detail: string | null, durationMs: number | null): LiveRow {
  return {
    ...job,
    ok: false,
    status: null,
    detected: false,
    selector: false,
    state: false,
    frames: false,
    action: false,
    changed: false,
    restore: null,
    error,
    detail,
    duration_ms: durationMs,
    evidence_selector: null,
    changes: [],
    note: null,
    frame_hashes: null,
    t0: null,
    t1: null,
  };
}

function writeJson(path: string, value: unknown) {
  mkdirSync(dirname(path), { recursive: true });
  const tmp = `${path}.tmp`;
  writeFileSync(tmp, JSON.stringify(value, null, 2));
  renameSync(tmp, path);
}

function writeLedger(rows: LiveRow[]) {
  const recorded: RecordedInteractionRun[] = rows.map((row) => ({
    type: row.type,
    region: row.region,
    mode: row.mode,
    ok: row.ok,
    status: row.status,
    detected: row.detected,
    selector: row.selector,
    state: row.state,
    frames: row.frames,
    action: row.action,
    changed: row.changed === true,
    restore: row.restore,
  }));
  const body = `import type { RecordedInteractionRun } from "@/lib/interaction-completion";

/** Generated by scripts/run-interaction-completion-live.ts from Browserless fixture sessions. */
export const RECORDED_INTERACTION_RUNS: RecordedInteractionRun[] = ${JSON.stringify(recorded, null, 2)};
`;
  writeFileSync(LEDGER_PATH, body);
}

function matrixText(rows: LiveRow[]): string {
  const ledger = deriveInteractionCompletion(rows);
  const lines: string[] = [];
  lines.push(`runs ${rows.length}`);
  for (const type of INTERACTION_CHECK_TYPES) {
    const gates = ledger[type];
    const failed = INTERACTION_COMPLETION_GATES.filter((gate) => !gates[gate]);
    const mark = failed.length === 0 ? "COMPLETE" : "OPEN";
    lines.push(`${mark}\t${type}\t${failed.join(",") || "-"}`);
    const related = rows.filter((row) => row.type === type);
    for (const row of related) {
      const evidence =
        row.ok && (row.selector || row.state || row.frames)
          ? `selector=${row.evidence_selector ?? ""} changes=${row.changes.join("|")} note=${row.note ?? ""}`
          : row.error
            ? `error=${row.error}`
            : "no element evidence";
      lines.push(
        `  ${row.region} ${row.mode} status=${row.status ?? "none"} detected=${row.detected} restore=${row.restore ?? "none"} ${evidence}`,
      );
    }
  }
  return lines.join("\n");
}

function annotate(row: LiveRow): LiveRow {
  const hashes = Array.isArray(row.frame_hashes) ? row.frame_hashes.filter((item) => typeof item === "string") : null;
  const frames = hashes ? framesDiffer(hashes) : false;
  return {
    ...row,
    frames,
    frame_hashes: hashes,
    changed: snapshotsDiffer(row.t0, row.t1) || noteShowsDelta(row.note) || frames,
  };
}

function selectedJobs(jobs: Job[]): Job[] {
  const filter = (process.env.FIXTURE_JOB ?? "").trim();
  if (!filter) return jobs;
  const parts = filter.split(",").map((part) => part.trim()).filter(Boolean);
  return jobs.filter((job) =>
    parts.some((part) => part === job.type || part === jobKey(job) || part === `${job.region}:${job.mode}`),
  );
}

async function main() {
  if (process.env.REBUILD === "1") {
    const rows = loadRows().map(annotate);
    writeJson(RESULTS_PATH, rows);
    writeLedger(rows);
    const text = matrixText(rows);
    mkdirSync(dirname(MATRIX_PATH), { recursive: true });
    writeFileSync(MATRIX_PATH, text);
    console.log(text);
    return;
  }
  const { runBrowserlessScrollWithProxyRetry } = await import("../src/lib/browserless-scroll-interaction");
  const saved = loadRows();
  const byKey = new Map(saved.map((row) => [jobKey(row), row]));
  const pending = selectedJobs(allJobs()).filter((job) => !byKey.has(jobKey(job)));
  const concurrency = Math.max(1, Number(process.env.CONCURRENCY ?? "3") || 3);
  console.error(`pending ${pending.length} saved ${saved.length} concurrency ${concurrency}`);

  let chain = Promise.resolve();
  const exclusive = (fn: () => void) => {
    const run = chain.then(fn, fn);
    chain = run.then(
      () => undefined,
      () => undefined,
    );
    return run;
  };

  let cursor = 0;
  async function worker() {
    while (cursor < pending.length) {
      const job = pending[cursor];
      cursor += 1;
      if (!job) return;
      const url = `https://viewtrace.net/tests/interactions/${job.type}?mode=${job.mode}`;
      console.error(`running ${jobKey(job)}`);
      const started = Date.now();
      let row: LiveRow;
      try {
        const result = await runBrowserlessScrollWithProxyRetry({
          url,
          region: job.region,
          fixtureHtml: interactionFixtureDocument(job.type, job.mode),
        });
        if (!result.ok) {
          row = blank(job, result.error, result.detail ?? null, result.durationMs);
        } else {
          const typeRow = result.check.types.find((item) => item.type === job.type);
          const evidence = typeRow?.evidence ?? null;
          row = {
            ...job,
            ok: true,
            status: typeRow?.status ?? null,
            detected: typeRow?.detected === true,
            selector: Boolean(evidence?.selector),
            state: Boolean(evidence?.t0 && evidence?.t1),
            frames: framesDiffer(
              Array.isArray(evidence?.frame_hashes)
                ? evidence.frame_hashes.filter((item): item is string => typeof item === "string")
                : null,
            ),
            action: Array.isArray(evidence?.actions) && evidence.actions.length > 0,
            changed: false,
            restore: evidence?.restore === "ok" || evidence?.restore === "failed" ? evidence.restore : null,
            error: null,
            detail: null,
            duration_ms: result.durationMs,
            evidence_selector: evidence?.selector ?? null,
            changes: evidence?.changes ?? [],
            note: evidence?.note ?? null,
            frame_hashes: Array.isArray(evidence?.frame_hashes)
              ? evidence.frame_hashes.filter((item): item is string => typeof item === "string").slice(0, 2)
              : null,
            t0: evidence?.t0 ?? null,
            t1: evidence?.t1 ?? null,
          };
          row = annotate(row);
        }
      } catch (error) {
        row = blank(job, "exception", error instanceof Error ? error.message : String(error), Date.now() - started);
      }
      console.error(
        `done ${jobKey(job)} status=${row.status ?? "none"} ok=${row.ok} ${row.error ?? ""} ${Math.round((row.duration_ms ?? 0) / 1000)}s`,
      );
      await exclusive(() => {
        byKey.set(jobKey(job), row);
        const rows = [...byKey.values()];
        writeJson(RESULTS_PATH, rows);
        writeLedger(rows);
      });
    }
  }

  await Promise.all(Array.from({ length: Math.min(concurrency, Math.max(pending.length, 1)) }, () => worker()));
  const rows = [...byKey.values()];
  const text = matrixText(rows);
  writeJson(RESULTS_PATH, rows);
  writeLedger(rows);
  mkdirSync(dirname(MATRIX_PATH), { recursive: true });
  writeFileSync(MATRIX_PATH, text);
  console.log(text);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
